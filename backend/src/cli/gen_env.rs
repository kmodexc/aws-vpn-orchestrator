//! `gen-env`: print a complete `.env` with freshly generated secrets.

use std::fmt::Write as _;

use crate::util::{b64std, b64url, clamp_x25519, random_bytes, random_token, x25519_public};

/// The default SNI the generated Hysteria2 certificate is issued for.
pub const DEFAULT_HY2_SNI: &str = "www.bing.com";

/// Generate every secret value. Returned as `(VARIABLE, value)` pairs.
pub fn generate_secrets() -> anyhow::Result<Vec<(&'static str, String)>> {
    let sub_token = random_token()?;
    let ingress_token = random_token()?;
    // Version 4 / RFC 4122 variant bits are set by the builder.
    let vless_uuid = uuid::Builder::from_random_bytes(random_bytes::<16>()?)
        .into_uuid()
        .hyphenated()
        .to_string();

    let reality_private = clamp_x25519(random_bytes::<32>()?);
    let reality_public = x25519_public(reality_private);
    let short_id = hex::encode(random_bytes::<8>()?);
    let hy2_password = b64url(&random_bytes::<24>()?);
    let (cert_pem, key_pem) = self_signed_cert(DEFAULT_HY2_SNI)?;
    let ss_password = b64std(&random_bytes::<16>()?);
    let wg_private = clamp_x25519(random_bytes::<32>()?);

    Ok(vec![
        ("SUB_TOKEN", sub_token),
        ("INGRESS_TOKEN", ingress_token),
        ("VLESS_UUID", vless_uuid),
        ("REALITY_PRIVATE_KEY", b64url(&reality_private)),
        ("REALITY_PUBLIC_KEY", b64url(&reality_public)),
        ("REALITY_SHORT_ID", short_id),
        ("HY2_PASSWORD", hy2_password),
        ("HY2_CERT_PEM_B64", b64std(cert_pem.as_bytes())),
        ("HY2_KEY_PEM_B64", b64std(key_pem.as_bytes())),
        ("SS_PASSWORD", ss_password),
        ("WG_INGRESS_PRIVATE_KEY", b64std(&wg_private)),
    ])
}

/// Self-signed ECDSA P-256 certificate with CN and SAN = `sni`. Returns (cert PEM, key PEM).
fn self_signed_cert(sni: &str) -> anyhow::Result<(String, String)> {
    let key = rcgen::KeyPair::generate_for(&rcgen::PKCS_ECDSA_P256_SHA256)?;
    let mut params = rcgen::CertificateParams::new(vec![sni.to_string()])?;
    let mut dn = rcgen::DistinguishedName::new();
    dn.push(rcgen::DnType::CommonName, sni);
    params.distinguished_name = dn;
    let cert = params.self_signed(&key)?;
    Ok((cert.pem(), key.serialize_pem()))
}

/// Render the full `.env` file.
pub fn render() -> anyhow::Result<String> {
    let secrets = generate_secrets()?;
    let get = |name: &str| -> String {
        secrets
            .iter()
            .find(|(k, _)| *k == name)
            .map(|(_, v)| v.clone())
            .unwrap_or_default()
    };
    let wg_public = {
        use base64::Engine;
        let raw = base64::engine::general_purpose::STANDARD
            .decode(get("WG_INGRESS_PRIVATE_KEY"))
            .ok()
            .and_then(|b| <[u8; 32]>::try_from(b.as_slice()).ok());
        raw.map(|k| b64std(&x25519_public(k))).unwrap_or_default()
    };

    let mut out = String::new();
    let mut line = |s: &str| {
        let _ = writeln!(out, "{s}");
    };
    line("# vpn-control configuration. Generated by `vpn-control gen-env`.");
    line("# KEEP THIS FILE SECRET. Never commit it and never bake it into an image.");
    line("# Fill in every empty value below, then: docker compose up -d");
    line("");
    line("# --- Public endpoint (used by the Apache vhost and the backend) ---");
    line("DOMAIN=");
    line("# Must be https://<DOMAIN> without trailing slash");
    line("PUBLIC_BASE_URL=");
    line("");
    line("# --- Docker / host ---");
    line("# Host port on 127.0.0.1 that Apache proxies to. Convention 1xxyy:");
    line("# xx = id of this compose stack (01-99), yy = 01 (the only forwarded port).");
    line("APP_HOST_PORT=11001");
    line("# Image to run (built by GitHub Actions). Pin a commit tag, e.g. :sha-1a2b3c4");
    line("VPN_CONTROL_IMAGE=ghcr.io/kmodexc/aws-vpn-orchestrator:latest");
    line("");
    line("# --- Server ---");
    line("BIND_ADDR=0.0.0.0:8080");
    line("RUST_LOG=info");
    line("LOG_FORMAT=json");
    line("# true behind Apache: client IP = right-most X-Forwarded-For entry");
    line("TRUST_PROXY_HEADERS=true");
    line("STATE_DIR=/data");
    line("STATIC_DIR=/app/static");
    line("");
    line("# --- OIDC (Keycloak at https://auth.kmode.dev) ---");
    line("OIDC_ISSUER_URL=https://auth.kmode.dev/realms/CHANGE_ME");
    line("OIDC_CLIENT_ID=console");
    line("OIDC_CLIENT_SECRET=");
    line("OIDC_REQUIRED_ROLE=vpn-admin");
    line("# Role that may only sign in and read the subscription (no controls)");
    line("OIDC_USER_ROLE=vpn-user");
    line(
        "# Comma list of client ids whose Bearer tokens are accepted (azp); default OIDC_CLIENT_ID",
    );
    line("OIDC_ALLOWED_CLIENTS=console");
    line("OIDC_SCOPES=\"openid profile email\"");
    line("SESSION_IDLE_TIMEOUT_S=1800");
    line("SESSION_ABSOLUTE_TIMEOUT_S=43200");
    line("");
    line("# --- Ingress provider: lightsail | ec2 | fake (fake = local development only) ---");
    line("PROVIDER=lightsail");
    line("AWS_REGION=");
    line("AWS_ACCESS_KEY_ID=");
    line("AWS_SECRET_ACCESS_KEY=");
    line("# Lightsail instance name or EC2 instance id (i-...)");
    line("INGRESS_INSTANCE=");
    line("ROTATE_COOLDOWN_S=120");
    line("");
    line("# --- Path tokens (secret, >= 32 chars of [A-Za-z0-9_-]) ---");
    line(&format!("SUB_TOKEN={}", get("SUB_TOKEN")));
    line(&format!("INGRESS_TOKEN={}", get("INGRESS_TOKEN")));
    line("");
    line("# --- Subscription ---");
    line("PROFILE_NAME=travel");
    line("SUB_UPDATE_HOURS=1");
    line("");
    line("# --- sing-box protocols ---");
    line("REALITY_SNI=www.microsoft.com");
    line(
        "# The Hysteria2 certificate below is issued for this name; regenerate it if you change it",
    );
    line(&format!("HY2_SNI={DEFAULT_HY2_SNI}"));
    line("VLESS_PORT=443");
    line("HY2_PORT=443");
    line("SS_PORT=8443");
    line(&format!("VLESS_UUID={}", get("VLESS_UUID")));
    line(&format!(
        "REALITY_PRIVATE_KEY={}",
        get("REALITY_PRIVATE_KEY")
    ));
    line(&format!("REALITY_PUBLIC_KEY={}", get("REALITY_PUBLIC_KEY")));
    line(&format!("REALITY_SHORT_ID={}", get("REALITY_SHORT_ID")));
    line(&format!("HY2_PASSWORD={}", get("HY2_PASSWORD")));
    line(&format!("HY2_CERT_PEM_B64={}", get("HY2_CERT_PEM_B64")));
    line(&format!("HY2_KEY_PEM_B64={}", get("HY2_KEY_PEM_B64")));
    line(&format!("SS_PASSWORD={}", get("SS_PASSWORD")));
    line("");
    line("# --- Optional WireGuard exit from the ingress to the VPS ---");
    line("WG_ENABLED=false");
    line("# host:port of the WireGuard listener on the VPS");
    line("WG_VPS_ENDPOINT=");
    line("WG_VPS_PUBLIC_KEY=");
    line(&format!(
        "# Ingress public key (for the VPS peer config): {wg_public}"
    ));
    line(&format!(
        "WG_INGRESS_PRIVATE_KEY={}",
        get("WG_INGRESS_PRIVATE_KEY")
    ));
    line("WG_INGRESS_ADDRESS=10.66.0.2/32");
    line("WG_MTU=1380");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_contains_every_variable_once() {
        let out = render().unwrap();
        for var in [
            "DOMAIN",
            "PUBLIC_BASE_URL",
            "OIDC_CLIENT_SECRET",
            "SUB_TOKEN",
            "INGRESS_TOKEN",
            "HY2_CERT_PEM_B64",
            "WG_MTU",
        ] {
            let prefix = format!("{var}=");
            assert_eq!(
                out.lines().filter(|l| l.starts_with(&prefix)).count(),
                1,
                "{var}"
            );
        }
    }

    #[test]
    fn generated_secrets_have_expected_shapes() {
        let s = generate_secrets().unwrap();
        let get = |k: &str| s.iter().find(|(n, _)| *n == k).unwrap().1.clone();
        assert_eq!(get("SUB_TOKEN").len(), 43);
        assert_eq!(get("REALITY_SHORT_ID").len(), 16);
        assert_eq!(get("REALITY_PRIVATE_KEY").len(), 43);
        assert_eq!(get("SS_PASSWORD").len(), 24);
        assert_eq!(get("WG_INGRESS_PRIVATE_KEY").len(), 44);
        let uuid = uuid::Uuid::parse_str(&get("VLESS_UUID")).unwrap();
        assert_eq!(uuid.get_version_num(), 4);
    }
}
